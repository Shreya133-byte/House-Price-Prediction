from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from sklearn.linear_model import Ridge
from sklearn.ensemble import (
    RandomForestRegressor,
    GradientBoostingRegressor,
    HistGradientBoostingRegressor
)

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

import numpy as np
import pandas as pd

print("=" * 70)
print("TRAIN / TEST SPLIT + PREPROCESSING + MODEL TRAINING")
print("=" * 70)


# ============================================================
# 1. REBUILD FEATURES FROM ORIGINAL DATA
#    This ensures preprocessing does not leak test information.
# ============================================================

data = df.copy()

# Separate target
X = data.drop(columns=["SalePrice"]).copy()
y = data["SalePrice"].copy()

# Remove ID because it does not represent a meaningful property feature
if "Id" in X.columns:
    X = X.drop(columns=["Id"])

# ============================================================
# 2. FEATURE ENGINEERING
# ============================================================

if {"TotalBsmtSF", "1stFlrSF", "2ndFlrSF"}.issubset(X.columns):
    X["TotalSF"] = (
        X["TotalBsmtSF"]
        + X["1stFlrSF"]
        + X["2ndFlrSF"]
    )

if {
    "FullBath",
    "HalfBath",
    "BsmtFullBath",
    "BsmtHalfBath"
}.issubset(X.columns):

    X["TotalBathrooms"] = (
        X["FullBath"]
        + 0.5 * X["HalfBath"]
        + X["BsmtFullBath"]
        + 0.5 * X["BsmtHalfBath"]
    )

porch_features = [
    "OpenPorchSF",
    "EnclosedPorch",
    "3SsnPorch",
    "ScreenPorch",
    "WoodDeckSF"
]

available_porch = [
    col for col in porch_features
    if col in X.columns
]

if available_porch:
    X["TotalPorchSF"] = X[available_porch].sum(axis=1)

# ============================================================
# 3. TRAIN / TEST SPLIT
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("\n📌 Dataset Split")
print(f"Training samples : {X_train.shape[0]}")
print(f"Testing samples  : {X_test.shape[0]}")


# ============================================================
# 4. IDENTIFY FEATURE TYPES
# ============================================================

numeric_features = X_train.select_dtypes(
    include=np.number
).columns.tolist()

categorical_features = X_train.select_dtypes(
    include=["object", "category"]
).columns.tolist()

print(f"\nNumerical features   : {len(numeric_features)}")
print(f"Categorical features : {len(categorical_features)}")


# ============================================================
# 5. NUMERICAL PREPROCESSING
# ============================================================

numeric_pipeline = Pipeline(
    steps=[
        (
            "imputer",
            SimpleImputer(strategy="median")
        ),
        (
            "scaler",
            StandardScaler()
        )
    ]
)


# ============================================================
# 6. CATEGORICAL PREPROCESSING
# ============================================================

categorical_pipeline = Pipeline(
    steps=[
        (
            "imputer",
            SimpleImputer(strategy="most_frequent")
        ),
        (
            "encoder",
            OneHotEncoder(
                handle_unknown="ignore",
                sparse_output=False
            )
        )
    ]
)


# ============================================================
# 7. COMBINE PREPROCESSING
# ============================================================

preprocessor = ColumnTransformer(
    transformers=[
        (
            "num",
            numeric_pipeline,
            numeric_features
        ),
        (
            "cat",
            categorical_pipeline,
            categorical_features
        )
    ]
)


# ============================================================
# 8. LOG TRANSFORM TARGET
# ============================================================

y_train_log = np.log1p(y_train)
y_test_log = np.log1p(y_test)

print("\n✅ Target transformed using log1p().")


# ============================================================
# 9. DEFINE MODELS
# ============================================================

models = {

    "Ridge Regression": Ridge(
        alpha=10.0
    ),

    "Random Forest": RandomForestRegressor(
        n_estimators=300,
        max_depth=None,
        min_samples_split=2,
        random_state=42,
        n_jobs=-1
    ),

    "Gradient Boosting": GradientBoostingRegressor(
        n_estimators=300,
        learning_rate=0.05,
        max_depth=3,
        random_state=42
    ),

    "Hist Gradient Boosting": HistGradientBoostingRegressor(
        max_iter=300,
        learning_rate=0.05,
        max_leaf_nodes=31,
        random_state=42
    )
}


# ============================================================
# 10. TRAIN AND EVALUATE MODELS
# ============================================================

results = []
trained_models = {}

for model_name, model in models.items():

    print("\n" + "-" * 70)
    print(f"Training: {model_name}")

    pipeline = Pipeline(
        steps=[
            ("preprocessor", preprocessor),
            ("model", model)
        ]
    )

    # Train
    pipeline.fit(
        X_train,
        y_train_log
    )

    # Predict log prices
    predictions_log = pipeline.predict(X_test)

    # Convert predictions back to original price scale
    predictions = np.expm1(predictions_log)

    # Prevent negative predictions
    predictions = np.maximum(predictions, 0)

    # Metrics
    mae = mean_absolute_error(
        y_test,
        predictions
    )

    rmse = np.sqrt(
        mean_squared_error(
            y_test,
            predictions
        )
    )

    r2 = r2_score(
        y_test,
        predictions
    )

    # RMSLE
    rmsle = np.sqrt(
        mean_squared_error(
            np.log1p(y_test),
            np.log1p(predictions)
        )
    )

    results.append({
        "Model": model_name,
        "MAE": mae,
        "RMSE": rmse,
        "RMSLE": rmsle,
        "R2 Score": r2
    })

    trained_models[model_name] = pipeline

    print(f"MAE   : ${mae:,.2f}")
    print(f"RMSE  : ${rmse:,.2f}")
    print(f"RMSLE : {rmsle:.4f}")
    print(f"R²    : {r2:.4f}")


# ============================================================
# 11. MODEL COMPARISON
# ============================================================

results_df = pd.DataFrame(results)

results_df = results_df.sort_values(
    by="RMSLE",
    ascending=True
).reset_index(drop=True)

print("\n" + "=" * 70)
print("MODEL COMPARISON")
print("=" * 70)

display(
    results_df.style.format({
        "MAE": "${:,.2f}",
        "RMSE": "${:,.2f}",
        "RMSLE": "{:.4f}",
        "R2 Score": "{:.4f}"
    })
)


# ============================================================
# 12. SELECT BEST MODEL
# ============================================================

best_model_name = results_df.iloc[0]["Model"]
best_model = trained_models[best_model_name]

print("\n🏆 BEST MODEL")
print(f"Model : {best_model_name}")

print("\nBest model performance:")

best_result = results_df.iloc[0]

print(f"MAE   : ${best_result['MAE']:,.2f}")
print(f"RMSE  : ${best_result['RMSE']:,.2f}")
print(f"RMSLE : {best_result['RMSLE']:.4f}")
print(f"R²    : {best_result['R2 Score']:.4f}")

print("\n✅ MODEL TRAINING COMPLETED")

